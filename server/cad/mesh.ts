/**
 * A small mesh kernel so Forge can produce printable 3D parts with no CAD program installed.
 * Parts are placed side by side (no boolean operations); each part also gets an OpenSCAD
 * equivalent so the design can be refined in real CAD later.
 */

export type Vec3 = [number, number, number];
export type Triangle = [Vec3, Vec3, Vec3];

export type Part =
  | { shape: "box"; size: Vec3; at?: Vec3 }
  | { shape: "cylinder"; radius: number; height: number; at?: Vec3 }
  | { shape: "sphere"; radius: number; at?: Vec3 };

const SEGMENTS = 32;

function add(a: Vec3, b: Vec3): Vec3 {
  return [a[0] + b[0], a[1] + b[1], a[2] + b[2]];
}

/** Axis-aligned box with its minimum corner at `at`. */
export function box(size: Vec3, at: Vec3 = [0, 0, 0]): Triangle[] {
  const [x, y, z] = size;
  const v = (i: number, j: number, k: number): Vec3 => add(at, [i * x, j * y, k * z]);
  const quads: Vec3[][] = [
    [v(0, 0, 0), v(0, 1, 0), v(1, 1, 0), v(1, 0, 0)], // bottom (-z)
    [v(0, 0, 1), v(1, 0, 1), v(1, 1, 1), v(0, 1, 1)], // top (+z)
    [v(0, 0, 0), v(1, 0, 0), v(1, 0, 1), v(0, 0, 1)], // front (-y)
    [v(0, 1, 0), v(0, 1, 1), v(1, 1, 1), v(1, 1, 0)], // back (+y)
    [v(0, 0, 0), v(0, 0, 1), v(0, 1, 1), v(0, 1, 0)], // left (-x)
    [v(1, 0, 0), v(1, 1, 0), v(1, 1, 1), v(1, 0, 1)], // right (+x)
  ];
  return quads.flatMap(([a, b, c, d]) => [[a, b, c], [a, c, d]] as Triangle[]);
}

/** Upright cylinder whose base centre sits at `at`. */
export function cylinder(radius: number, height: number, at: Vec3 = [0, 0, 0]): Triangle[] {
  const tris: Triangle[] = [];
  const ring = (z: number) =>
    Array.from({ length: SEGMENTS }, (_, i): Vec3 => {
      const t = (i / SEGMENTS) * Math.PI * 2;
      return add(at, [radius * Math.cos(t), radius * Math.sin(t), z]);
    });
  const bottom = ring(0);
  const top = ring(height);
  const cb = add(at, [0, 0, 0]);
  const ct = add(at, [0, 0, height]);
  for (let i = 0; i < SEGMENTS; i++) {
    const j = (i + 1) % SEGMENTS;
    tris.push([cb, bottom[j], bottom[i]]);
    tris.push([ct, top[i], top[j]]);
    tris.push([bottom[i], bottom[j], top[j]]);
    tris.push([bottom[i], top[j], top[i]]);
  }
  return tris;
}

/** UV sphere centred on `at`. */
export function sphere(radius: number, at: Vec3 = [0, 0, 0]): Triangle[] {
  const rows = SEGMENTS / 2;
  const point = (r: number, c: number): Vec3 => {
    const phi = (r / rows) * Math.PI;
    const theta = (c / SEGMENTS) * Math.PI * 2;
    return add(at, [
      radius * Math.sin(phi) * Math.cos(theta),
      radius * Math.sin(phi) * Math.sin(theta),
      radius * Math.cos(phi),
    ]);
  };
  const tris: Triangle[] = [];
  for (let r = 0; r < rows; r++) {
    for (let c = 0; c < SEGMENTS; c++) {
      const a = point(r, c), b = point(r + 1, c), d = point(r, c + 1), e = point(r + 1, c + 1);
      if (r > 0) tris.push([a, b, d]);
      if (r < rows - 1) tris.push([d, b, e]);
    }
  }
  return tris;
}

export function partMesh(part: Part): Triangle[] {
  switch (part.shape) {
    case "box": return box(part.size, part.at);
    case "cylinder": return cylinder(part.radius, part.height, part.at);
    case "sphere": return sphere(part.radius, part.at);
  }
}

function normal([a, b, c]: Triangle): Vec3 {
  const u: Vec3 = [b[0] - a[0], b[1] - a[1], b[2] - a[2]];
  const v: Vec3 = [c[0] - a[0], c[1] - a[1], c[2] - a[2]];
  const n: Vec3 = [u[1] * v[2] - u[2] * v[1], u[2] * v[0] - u[0] * v[2], u[0] * v[1] - u[1] * v[0]];
  const len = Math.hypot(...n) || 1;
  return [n[0] / len, n[1] / len, n[2] / len];
}

const num = (n: number) => Number(n.toFixed(5)).toString();

export function toAsciiStl(name: string, tris: Triangle[]): string {
  const lines = [`solid ${name}`];
  for (const tri of tris) {
    lines.push(`  facet normal ${normal(tri).map(num).join(" ")}`, "    outer loop");
    for (const p of tri) lines.push(`      vertex ${p.map(num).join(" ")}`);
    lines.push("    endloop", "  endfacet");
  }
  lines.push(`endsolid ${name}`);
  return lines.join("\n") + "\n";
}

export function toScad(parts: Part[]): string {
  const body = parts.map((p) => {
    const at = p.at ?? [0, 0, 0];
    const shape =
      p.shape === "box" ? `cube([${p.size.join(", ")}]);`
      : p.shape === "cylinder" ? `cylinder(r = ${p.radius}, h = ${p.height}, $fn = ${SEGMENTS});`
      : `sphere(r = ${p.radius}, $fn = ${SEGMENTS});`;
    return `  translate([${at.join(", ")}]) ${shape}`;
  });
  return `// Generated by Forge. Edit freely and render with the openscad_render tool.\nunion() {\n${body.join("\n")}\n}\n`;
}

export function bounds(tris: Triangle[]): { min: Vec3; max: Vec3 } {
  const min: Vec3 = [Infinity, Infinity, Infinity];
  const max: Vec3 = [-Infinity, -Infinity, -Infinity];
  for (const tri of tris) for (const p of tri) for (let i = 0; i < 3; i++) {
    min[i] = Math.min(min[i], p[i]);
    max[i] = Math.max(max[i], p[i]);
  }
  return { min, max };
}
