use super::{route, PreparedBoard};
use std::collections::{BTreeMap, BTreeSet};

fn ascii(value: &str) -> String {
    value.chars().map(|c| if c.is_ascii_graphic() { c } else { '?' }).collect()
}

fn record(net: &str, reference: &str, pin: &str, p: &route::Pad, access: usize, mask: u8, midpoint: bool) -> String {
    let size = |v: f64| (v * 1000.).round().clamp(0., 9999.) as i64;
    let coord = |v: f64| (v * 1000.).round().clamp(-999999., 999999.) as i64;
    let hole = p.drill.map(|d| format!("D{:04}{}", size(d[0].min(d[1])), if p.plated { 'P' } else { 'U' }))
        .unwrap_or_else(|| "      ".into());
    let reference: String = ascii(reference).chars().take(6).collect();
    let pin: String = ascii(pin).chars().take(4).collect();
    let y = if p.round && p.size[0] == p.size[1] { 0. } else { p.size[1] };
    format!("{}{:14}   {reference:6}{}{pin:4}{}{hole}A{access:02}X{:+07}Y{:+07}X{:04}Y{:04}R{:03}S{mask}\n",
        if p.drill.is_some() { "317" } else { "327" }, net,
        if pin.is_empty() { ' ' } else { '-' }, if midpoint { 'M' } else { ' ' },
        coord(p.at[0]), coord(p.at[1]), size(p.size[0]), size(y),
        (-p.rotation).rem_euclid(360.).round() as usize % 360)
}

pub(super) fn netlist(prepared: &PreparedBoard, b: &route::Board, r: &route::Routes, name: &str) -> String {
    let mut out = format!("C  IPC-D-356A netlist generated by Forge {}\nC  File: {name}\nP  JOB   {name}\nP  CODE  00\nP  UNITS CUST 1\nP  DIM   N\nP  VER   IPC-D-356A\nP  IMAGE PRIMARY\nC\n", env!("CARGO_PKG_VERSION"));
    let mut used: BTreeSet<_> = b.nets.iter().map(|n| ascii(&n.name).to_ascii_uppercase()).collect();
    used.insert("N/C".into());
    let mut names = BTreeMap::new();
    let mut alias_index = 0;
    for net in &b.nets {
        let canonical = ascii(&net.name).to_ascii_uppercase();
        let collision = b.nets.iter().filter(|n| ascii(&n.name).to_ascii_uppercase() == canonical).count() > 1;
        let short = if canonical.len() > 14 || canonical == "N/C" || collision {
            let alias = loop {
                alias_index += 1;
                let alias = format!("NNAME{alias_index}");
                if used.insert(alias.clone()) { break alias; }
            };
            let full: String = net.name.chars().map(|c| if c.is_ascii() { c } else { '?' }).collect();
            out.push_str(&format!("P  {alias:<11}{full}\n"));
            alias
        } else { canonical };
        names.insert(net.name.as_str(), short);
    }
    let net = |n: usize| b.nets.get(n).and_then(|n| names.get(n.name.as_str())).map(|s| s.as_str()).unwrap_or("N/C");
    for part in &prepared.spec.parts {
        let mut pads: Vec<_> = b.pads.iter().filter(|p| p.name.rsplit_once('.').is_some_and(|(reference, _)| reference == part.reference)).collect();
        pads.sort_by_key(|p| {
            let pin = p.name.rsplit_once('.').unwrap().1;
            (pin.parse::<usize>().unwrap_or(usize::MAX), pin)
        });
        for p in pads {
            let pin = p.name.rsplit_once('.').unwrap().1;
            let top = p.layers & 1 != 0;
            let bottom = p.layers & 2 != 0;
            let access = if p.drill.is_some() || top && bottom { 0 } else if top { 1 } else { 2 };
            let mask = u8::from(!top) | (u8::from(!bottom) << 1);
            out.push_str(&record(net(p.net), &part.reference, pin, p, access, mask, false));
        }
    }
    for v in &r.vias {
        let top = v.on(0, b.layers);
        let bottom = v.on(1, b.layers);
        let access = if top && bottom { 0 } else if top { 1 } else if bottom { 2 } else { v.span.0 + 1 };
        let pad = route::Pad { name: "VIA".into(), at: v.at, size: [b.via[0]; 2], rotation: 0., round: true,
            radius: 0., layers: v.mask(b.layers), drill: Some([b.via[1]; 2]), plated: true, net: v.net };
        out.push_str(&record(net(v.net), "VIA", "", &pad, access, u8::from(!top) | (u8::from(!bottom) << 1), true));
    }
    out.push_str("999\n");
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn metric_records_keep_fixed_columns_for_pad_smd_and_via() {
        let prepared = super::super::prepare(r#"{"board":{"width":20,"height":15},"parts":[{"ref":"J1","kind":"header","footprint":"pinheader_1x1","at":[-5,0]},{"ref":"R1","kind":"resistor","footprint":"0603","at":[5,0]}],"nets":{"N":["J1.1"]}}"#).unwrap();
        let mut b = route::Board::from_prepared(&prepared).unwrap();
        b.pads.retain(|p| p.name != "R1.2");
        b.pads[0].at = [-2., 3.]; b.pads[0].size = [1.7; 2]; b.pads[0].drill = Some([1.; 2]);
        b.pads[0].round = false;
        b.pads[1].at = [4., -1.]; b.pads[1].size = [1., 0.5]; b.pads[1].rotation = 90.;
        let r = route::Routes { tracks: vec![], vias: vec![route::Via { at: [0., -2.], net: 0, span: (0, 1) }],
            routed: vec![true], passes: 0, teardrops: vec![], fallback: vec![] };
        let out = netlist(&prepared, &b, &r, "tiny");
        // Columns: type 1-3, net 4-17, ref 21-26, pin 28-31, midpoint 32,
        // drill 33-38, access 39-41, XY 42-57, size 58-67, rotation 68-71, mask 72-73.
        let expected = [
            concat!("317", "N             ", "   ", "J1    ", "-", "1   ", " ", "D1000P", "A00", "X-002000", "Y+003000", "X1700", "Y1700", "R000", "S0"),
            concat!("327", "N/C           ", "   ", "R1    ", "-", "1   ", " ", "      ", "A01", "X+004000", "Y-001000", "X1000", "Y0500", "R270", "S2"),
            concat!("317", "N             ", "   ", "VIA   ", " ", "    ", "M", "D0300P", "A00", "X+000000", "Y-002000", "X0600", "Y0000", "R000", "S0"),
        ];
        assert_eq!(out.lines().filter(|l| l.starts_with("317") || l.starts_with("327")).collect::<Vec<_>>(), expected);
        assert!(expected.iter().all(|l| l.len() == 73));
        assert!(out.contains("P  UNITS CUST 1\nP  DIM   N\nP  VER   IPC-D-356A\n"));
        assert!(out.ends_with("999\n"));
        b.pads[1].layers = 2;
        assert!(netlist(&prepared, &b, &r, "tiny").contains("A02X+004000Y-001000X1000Y0500R270S1\n"));
        b.pads[0].plated = false; b.pads[0].layers = 0;
        assert!(netlist(&prepared, &b, &r, "tiny").contains("D1000UA00X-002000Y+003000X1700Y1700R000S3\n"));
        b.nets[0].name = "Long signal name with spaces".into();
        let out = netlist(&prepared, &b, &r, "tiny");
        assert!(out.contains("P  NNAME1     Long signal name with spaces\n"));
        assert!(out.lines().filter(|l| l.starts_with("317")).all(|l| l[3..17].trim() == "NNAME1"));
    }

    #[test]
    fn long_and_colliding_net_names_use_distinct_aliases() {
        let prepared = super::super::prepare(r#"{"board":{"width":20,"height":15},"nets":{"NNAME1":[],"SIGNAL_NAME_LONGER_THAN_14":[],"signal":[],"SIGNAL":[]}}"#).unwrap();
        let b = route::Board::from_prepared(&prepared).unwrap();
        let r = route::route(&b);
        let out = netlist(&prepared, &b, &r, "tiny");
        assert!(out.contains("P  NNAME3     SIGNAL_NAME_LONGER_THAN_14\n"));
        assert!(!out.contains("P  NNAME1 "));
        assert_eq!(out.matches("P  NNAME").count(), 3);
    }
}
